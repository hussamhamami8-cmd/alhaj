function cards(list = places) {

  const element = $("#placeGrid");

  if (!element) return;

  element.innerHTML = list.map((place, index) => `

    <article
      class="card"
      onclick="openPlace(${index})"
    >

      <img
        src="${place.image}"
        onerror="this.src='images/placeholder.svg'"
      >

      <div class="card-body">

        <span class="pill">
          ${place.tag}
        </span>

        <h3>
          ${place.name}
        </h3>

        <p>
          ${place.text}
        </p>

      </div>

    </article>

  `).join("");

}


